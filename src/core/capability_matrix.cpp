#include "core/capability_matrix.h"

namespace gno {

std::vector<CapabilityEntry> CapabilityMatrix::canDo(bool elevated) {
    std::vector<CapabilityEntry> list;
    const std::string admin_note = elevated ? "" : " - требуются права администратора";
    list.push_back({"DNS-серверы адаптера",
                    "Переключение между провайдерским DNS и 1.1.1.1/1.0.0.1 с бэкапом и откатом"});
    list.push_back({"Xbox Game DVR", "Включение/отключение записи клипов в фоне (реестр HKCU)"});
    list.push_back({"Оптимизация полного экрана",
                    "Отключение для игровых exe (совместимость, реестр HKCU)"});
    list.push_back({"TCP InitialRtt", "Параметр TCP/IP в реестре" + admin_note});
    list.push_back({"MTU интерфейса",
                    "Установка MTU 1500 для выбранного сетевого интерфейса" + admin_note});
    list.push_back({"План питания",
                    "Схема \"Высокая производительность\" через powercfg" + admin_note});
    list.push_back({"Приоритет процесса игры", "AboveNormal для запущенного процесса игры"});
    if (elevated) {
        list.push_back({"Файлы реестра Windows (разрешённые ключи)",
                        "Только ключи из белого списка GNO; каждое изменение с резервной копией и откатом"});
    } else {
        list.push_back({"Чтение состояния системы",
                        "Диагностика доступна всегда; изменения в HKLM - после запуска от администратора"});
    }
    return list;
}

std::vector<CapabilityEntry> CapabilityMatrix::cannotDo() {
    return {
        {"Изменять файлы игры",
         "GNO никогда не трогает файлы игры и лаунчера - только восстановление через официальный лаунчер"},
        {"Обходить или настраивать античит",
         "BattlEye/Vanguard/EAC защищены производителем; мы можем лишь проверить статус служб"},
        {"Снизить пинг до сервера игры",
         "Маршрут до серверов определяет провайдер; GNO измеряет и советует, но не перенаправляет трафик"},
        {"VPN/relay/проксирование трафика",
         "Осознанно не реализовано: требует внешней инфраструктуры и меняет приватность"},
        {"Разгон оборудования", "CPU/GPU/RAM вне зоны ответственности сетевого оптимизатора"},
        {"Обход блокировок провайдера",
         "Шейпинг и тарифная политика провайдера недоступны для изменения с клиента"},
        {"Менять системные файлы и драйверы",
         "Никаких изменений вне белого списка ключей реестра и параметров сети"},
        {"Гарантировать результат",
         "Каждое действие проверяется по факту; если цель не достигнута - используйте откат"},
    };
}

} // namespace gno
